fun main() {
    // String variable (val = immutable)
    val name: String = "Android"

    // Int variable
    val numberOfPhotos: Int = 100

    // Double variable
    val subscriptionPrice: Double = 9.99

    // Boolean variable
    val isLoggedIn: Boolean = true

    println("Name: $name")
    println("Number of photos: $numberOfPhotos")
    println("Subscription price: $subscriptionPrice")
    println("Is logged in: $isLoggedIn")
}
